CREATE TABLE IF NOT EXISTS bdr_leads (
  id CHAR(26) NOT NULL,
  customer_id CHAR(26) NOT NULL,
  campaign_id CHAR(26) NOT NULL,
  phone VARCHAR(20) NOT NULL,
  phone_display VARCHAR(40) NOT NULL,
  company VARCHAR(200) NULL,
  contact_name VARCHAR(200) NULL,
  source VARCHAR(32) NOT NULL,
  status VARCHAR(16) NOT NULL,
  attempts INT NOT NULL DEFAULT 0,
  last_outcome VARCHAR(32) NULL,
  next_attempt_at DATETIME(3) NULL,
  locked_by CHAR(26) NULL,
  locked_at DATETIME(3) NULL,
  lead_json JSON NOT NULL,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  deleted_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_bdr_leads_phone (customer_id, campaign_id, phone),
  KEY idx_bdr_leads_queue (customer_id, campaign_id, status, next_attempt_at),
  CONSTRAINT fk_bdr_leads_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
  CONSTRAINT fk_bdr_leads_campaign FOREIGN KEY (campaign_id) REFERENCES bdr_campaigns (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS bdr_dial_attempts (
  id CHAR(26) NOT NULL,
  customer_id CHAR(26) NOT NULL,
  user_id CHAR(26) NOT NULL,
  campaign_id CHAR(26) NULL,
  lead_id CHAR(26) NULL,
  call_id CHAR(26) NULL,
  phone VARCHAR(20) NOT NULL,
  operator_extension VARCHAR(40) NOT NULL,
  provider VARCHAR(32) NOT NULL,
  provider_call_id VARCHAR(64) NULL,
  status VARCHAR(16) NOT NULL,
  outcome VARCHAR(32) NULL,
  provider_seen TINYINT(1) NOT NULL DEFAULT 0,
  started_at DATETIME(3) NOT NULL,
  answered_at DATETIME(3) NULL,
  ended_at DATETIME(3) NULL,
  recording_status VARCHAR(16) NOT NULL DEFAULT 'none',
  recording_path VARCHAR(500) NULL,
  recording_tries INT NOT NULL DEFAULT 0,
  provider_json JSON NULL,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  PRIMARY KEY (id),
  KEY idx_bdr_attempts_user (customer_id, user_id, status),
  KEY idx_bdr_attempts_lead (customer_id, lead_id, started_at),
  KEY idx_bdr_attempts_recording (recording_status, ended_at),
  CONSTRAINT fk_bdr_attempts_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
  CONSTRAINT fk_bdr_attempts_user FOREIGN KEY (user_id) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS bdr_telephony_settings (
  customer_id CHAR(26) NOT NULL,
  provider VARCHAR(32) NOT NULL,
  base_url VARCHAR(200) NULL,
  api_token_enc VARCHAR(512) NULL,
  api_key_enc VARCHAR(512) NULL,
  device_id VARCHAR(40) NULL,
  dial_prefix VARCHAR(8) NOT NULL DEFAULT '0',
  ring_timeout_seconds INT NOT NULL DEFAULT 30,
  max_attempts INT NOT NULL DEFAULT 3,
  retry_busy_minutes INT NOT NULL DEFAULT 30,
  retry_no_answer_minutes INT NOT NULL DEFAULT 120,
  retry_voicemail_minutes INT NOT NULL DEFAULT 240,
  updated_at DATETIME(3) NOT NULL,
  PRIMARY KEY (customer_id),
  CONSTRAINT fk_bdr_telephony_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS bdr_operator_extensions (
  user_id CHAR(26) NOT NULL,
  customer_id CHAR(26) NOT NULL,
  extension VARCHAR(40) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  PRIMARY KEY (user_id),
  CONSTRAINT fk_bdr_extensions_user FOREIGN KEY (user_id) REFERENCES users (id),
  CONSTRAINT fk_bdr_extensions_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
